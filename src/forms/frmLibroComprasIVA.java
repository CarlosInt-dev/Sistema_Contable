    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed

        if (ordenSeleccionada == null) {
            JOptionPane.showMessageDialog(this, "Selecciona una orden de compra.");
            return;
        }

        String numeroDoc = txtNumeroDocumento.getText().trim();
        if (numeroDoc.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingresa el número de documento (factura).");
            return;
        }

        LibroComprasIVADAO dao = new LibroComprasIVADAO();

        // Validar que no exista ya esa factura para ese proveedor
        if (dao.existeFactura(idEmpresaActual, ordenSeleccionada.getIdProveedor(), numeroDoc)) {
            JOptionPane.showMessageDialog(this,
                    "Ya existe un registro con ese número de documento para este proveedor.");
            return;
        }

        BigDecimal total = ordenSeleccionada.getTotal();
        BigDecimal montoGravado = total.divide(UNO_MAS_IVA, 2, RoundingMode.HALF_UP);
        BigDecimal iva = total.subtract(montoGravado);

        LibroComprasIVA registro = new LibroComprasIVA(
                idEmpresaActual,
                ordenSeleccionada.getIdOrden(),
                ordenSeleccionada.getIdProveedor(),
                numeroDoc,
                Date.valueOf(LocalDate.now()),
                montoGravado,
                iva,
                total
        );

        boolean exito = dao.insertar(registro);

        if (exito) {
            JOptionPane.showMessageDialog(this, "Registro guardado en el libro de compras IVA.");
            limpiarFormulario();
            cargarOrdenesElegibles(); // refresca: esa orden ya no debe volver a aparecer
        } else {
            JOptionPane.showMessageDialog(this, "Error al guardar. Intenta de nuevo.");
        }

    }//GEN-LAST:event_btnGuardarActionPerformed

