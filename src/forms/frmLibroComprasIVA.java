    private void cargarOrdenesElegibles() {
        LibroComprasIVADAO dao = new LibroComprasIVADAO();
        List<OrdenCompra> elegibles = dao.listarOrdenesElegibles(idEmpresaActual);
        cmbOrdenCompra.removeAllItems();
        for (OrdenCompra o : elegibles) {
            cmbOrdenCompra.addItem(o);
        }
        if (cmbOrdenCompra.getItemCount() == 0) {
            JOptionPane.showMessageDialog(this,
                    "No hay órdenes recibidas pendientes de registrar en el libro de IVA.");
        }
    }

    private void cmbOrdenCompraActionPerformed(java.awt.event.ActionEvent evt) {
        ordenSeleccionada = (OrdenCompra) cmbOrdenCompra.getSelectedItem();
        if (ordenSeleccionada == null) {
            limpiarCamposAutollenados();
            return;
        }

        // Proveedor: necesitas el nombre, no solo el id.
        // Si OrdenCompra no trae el nombre del proveedor, lo buscamos aparte.
// Proveedor: usamos obtenerPorId, que devuelve el objeto Proveedor completo
        ProveedorDAO proveedorDAO = new ProveedorDAO();
        Proveedor proveedor = proveedorDAO.obtenerPorId(ordenSeleccionada.getIdProveedor(), idEmpresaActual);
        txtProveedor.setText(proveedor != null ? proveedor.getNombre() : "(Proveedor #" + ordenSeleccionada.getIdProveedor() + ")");
        BigDecimal total = ordenSeleccionada.getTotal();
        BigDecimal montoGravado = total.divide(UNO_MAS_IVA, 2, RoundingMode.HALF_UP);
        BigDecimal iva = total.subtract(montoGravado);

        txtMontoGrabado.setText(montoGravado.toString());
        txtIVA.setText(iva.toString());
        txtTotal.setText(total.toString());
    }

    private void limpiarCamposAutollenados() {
        txtProveedor.setText("");
        txtMontoGrabado.setText("");
        txtIVA.setText("");
        txtTotal.setText("");
    }

    private void limpiarFormulario() {
        txtNumeroDocumento.setText("");
        limpiarCamposAutollenados();
        ordenSeleccionada = null;
    }

    private BigDecimal calcularMontoGravado(BigDecimal total) {
        return total.divide(UNO_MAS_IVA, 2, java.math.RoundingMode.HALF_UP);
    }

    private BigDecimal calcularIva(BigDecimal total, BigDecimal montoGravado) {
        return total.subtract(montoGravado);
    }

